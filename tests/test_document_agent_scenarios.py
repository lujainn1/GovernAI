"""End-to-end scenario tests for the Document Processing Agent, run with
real generated files (real PDF bytes / real DOCX bytes) rather than mocked
extraction, plus their integration into the format the Risk/Policy agents
consume.

Covers the four required scenarios:
    1. English document (PDF)
    2. Arabic document (DOCX)
    3. Mixed Arabic/English document (DOCX)
    4. Scanned PDF requiring OCR (genuine image-only PDF, no text layer)

Arabic PDFs generated by fpdf2 (no bidi/shaping engine) come back from
pypdf with each RTL run's character order reversed - a known artifact of
naive PDF authoring, not something app.tools.language_detection or
document_extract can or should compensate for. detect_language() is
order-independent (it just counts script membership) so it isn't
affected, but substring-based document_type keyword matching would be, so
scenarios 2 and 3 use DOCX (Word XML stores Unicode in logical reading
order) to get a clean, representative round trip. Scenario 1 (English) and
4 (image-only scanned PDF) are unaffected by this and use real PDFs.

Run with: pytest tests/test_document_agent_scenarios.py -v -s
(the -s is needed to see the printed per-scenario report)
"""
import re
from io import BytesIO

import img2pdf
import pytest
from docx import Document
from fpdf import FPDF
from PIL import Image, ImageDraw, ImageFont

from app.agents.document_agent import DocumentProcessingAgent
from app.models import DocumentLanguage
from app.tools import ocr as ocr_module

FONT_PATH = "C:/Windows/Fonts/segoeui.ttf"


def _arabic(*codepoints: int) -> str:
    return "".join(chr(cp) for cp in codepoints)


ARABIC_SENTENCE = _arabic(
    # "hathihi siyasat al-khususiya lil-sharika. nahnu naltazim bi-himayat
    #  bayanat al-umala." (This is the company's privacy policy. We are
    #  committed to protecting customer data.)
    0x0647, 0x0630, 0x0647, 0x0020, 0x0633, 0x064A, 0x0627, 0x0633, 0x0629, 0x0020,
    0x0627, 0x0644, 0x062E, 0x0635, 0x0648, 0x0635, 0x064A, 0x0629, 0x0020,
    0x0644, 0x0644, 0x0634, 0x0631, 0x0643, 0x0629, 0x002E, 0x0020,
    0x0646, 0x0644, 0x062A, 0x0632, 0x0645, 0x0020,
    0x0628, 0x062D, 0x0645, 0x0627, 0x064A, 0x0629, 0x0020,
    0x0628, 0x064A, 0x0627, 0x0646, 0x0627, 0x062A, 0x0020,
    0x0627, 0x0644, 0x0639, 0x0645, 0x0644, 0x0627, 0x0621, 0x002E,
)

ENGLISH_PAGE_1 = (
    "Vendor Risk Assessment Report\n\n"
    "This document evaluates a third-party AI vendor's customer support "
    "system. The system processes customer email addresses and phone "
    "numbers to triage support tickets automatically."
)
ENGLISH_PAGE_2 = (
    "The vendor has confirmed SOC 2 Type II compliance and provides a "
    "human review step for any escalation the model flags as high risk."
)

SCANNED_IMAGE_TEXT = "This is a scanned document. OCR is required to extract this text."


def _report(scenario, result, passed, notes=""):
    print(f"\n{'=' * 70}")
    print(f"SCENARIO: {scenario}")
    print(f"{'=' * 70}")
    print(f"file_name        : {result.file_name}")
    print(f"file_type        : {result.file_type}")
    print(f"detected_language: {result.detected_language.value}")
    print(f"page_count       : {result.page_count}")
    print(f"ocr_used         : {result.ocr_used}")
    print(f"document_type    : {result.document_type}")
    print(f"word_count       : {result.word_count}")
    print(f"warnings         : {result.warnings or '(none)'}")
    print(f"extracted_text   :\n{result.extracted_text!r}")
    print(f"{'-' * 70}")
    print(f"RESULT: {'PASS' if passed else 'FAIL'}" + (f" - {notes}" if notes else ""))


# =========================================================
# Scenario 1: English document (PDF)
# =========================================================


def test_scenario_1_english_pdf():
    pdf = FPDF()
    pdf.add_page()
    pdf.add_font("Segoe", "", FONT_PATH)
    pdf.set_font("Segoe", size=12)
    pdf.multi_cell(190, 8, ENGLISH_PAGE_1)
    pdf.add_page()
    pdf.set_font("Segoe", size=12)
    pdf.multi_cell(190, 8, ENGLISH_PAGE_2)
    content = bytes(pdf.output())

    result = DocumentProcessingAgent().process("vendor_risk_assessment.pdf", content)

    # fpdf2's justified multi_cell() stretches lines to full width by
    # inserting extra spaces between words (pypdf's extraction faithfully
    # preserves that PDF-layer detail) - collapse whitespace runs before
    # substring checks so the test verifies *content*, not exact spacing.
    normalized_text = re.sub(r"\s+", " ", result.extracted_text)

    checks = {
        "file_type == pdf": result.file_type == "pdf",
        "detected_language == english": result.detected_language == DocumentLanguage.ENGLISH,
        "page_count == 2": result.page_count == 2,
        "ocr_used is False": result.ocr_used is False,
        "document_type == risk_assessment": result.document_type == "risk_assessment",
        "text contains page 1 content": "Vendor Risk Assessment" in normalized_text,
        "text contains page 2 content": "SOC 2" in normalized_text,
    }
    passed = all(checks.values())
    failed = [k for k, v in checks.items() if not v]
    _report("1. English document (PDF)", result, passed, notes="; ".join(failed))

    for check_name, ok in checks.items():
        assert ok, check_name


