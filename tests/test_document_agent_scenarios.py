# =========================================================
# Scenario 4a: Scanned PDF requiring OCR - REAL environment
# (no tesseract/poppler binaries installed here -> must degrade gracefully)
# =========================================================


def _make_scanned_pdf() -> bytes:
    image = Image.new("RGB", (900, 300), color="white")
    draw = ImageDraw.Draw(image)
    font = ImageFont.truetype(FONT_PATH, 28)
    draw.text((20, 120), SCANNED_IMAGE_TEXT, fill="black", font=font)
    img_buf = BytesIO()
    image.save(img_buf, format="PNG")
    return img2pdf.convert(img_buf.getvalue())


def test_scenario_4a_scanned_pdf_real_environment():
    content = _make_scanned_pdf()
    ocr_available = ocr_module.is_ocr_available()

    result = DocumentProcessingAgent().process("scanned_notice.pdf", content)

    checks = {
        "file_type == pdf": result.file_type == "pdf",
        "page_count == 1": result.page_count == 1,
        "pypdf text layer is empty (genuinely image-only)": result.word_count == 0
        or not ocr_available,
        "warnings explain missing text": bool(result.warnings),
    }
    passed = all(checks.values())
    failed = [k for k, v in checks.items() if not v]
    notes = "; ".join(failed)
    if not ocr_available:
        notes = (notes + "; " if notes else "") + (
            "NOTE: tesseract-ocr binary is not installed in this environment "
            "(requires admin rights to install) - OCR fallback correctly "
            "detected as unavailable and degraded gracefully instead of "
            "crashing. See test_scenario_4b for the OCR-available code path."
        )
    _report(
        f"4a. Scanned PDF requiring OCR (real environment, ocr_available={ocr_available})",
        result,
        passed,
        notes=notes,
    )

    for check_name, ok in checks.items():
        assert ok, check_name


# =========================================================
# Scenario 4b: Scanned PDF requiring OCR - SIMULATED OCR engine
# Proves the agent's OCR wiring/logic works correctly, using a monkeypatch
# to stand in for the tesseract binary this machine doesn't have installed.
# =========================================================


def test_scenario_4b_scanned_pdf_with_ocr_simulated(monkeypatch):
    content = _make_scanned_pdf()

    def fake_ocr_pdf(pdf_bytes, languages=ocr_module.DEFAULT_OCR_LANGUAGES):
        return SCANNED_IMAGE_TEXT, True

    monkeypatch.setattr("app.tools.document_extract.ocr_pdf", fake_ocr_pdf)

    result = DocumentProcessingAgent().process("scanned_notice.pdf", content)

    checks = {
        "file_type == pdf": result.file_type == "pdf",
        "page_count == 1": result.page_count == 1,
        "ocr_used is True": result.ocr_used is True,
        "detected_language == english": result.detected_language == DocumentLanguage.ENGLISH,
        "extracted_text == simulated OCR output": result.extracted_text == SCANNED_IMAGE_TEXT,
        "warnings mention OCR recovery": any("OCR" in w for w in result.warnings),
    }
    passed = all(checks.values())
    failed = [k for k, v in checks.items() if not v]
    _report(
        "4b. Scanned PDF requiring OCR (SIMULATED tesseract via monkeypatch)",
        result,
        passed,
        notes="; ".join(failed) or "SIMULATED - not a real tesseract OCR run",
    )

    for check_name, ok in checks.items():
        assert ok, check_name
